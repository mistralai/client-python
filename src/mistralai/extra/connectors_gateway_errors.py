import re
from typing import NamedTuple

import httpx2 as httpx

_GATEWAY_MEMBER = "connectors-gateway"

# RFC 8941 grammar subset for the Proxy-Status List (RFC 9209): Token or String members,
# each followed by parameters whose values are Strings or other bare items.
_TOKEN = r"[A-Za-z*][!#$%&'*+\-.^_`|~0-9A-Za-z:/]*"
_STRING = r'"((?:[\x20\x21\x23-\x5b\x5d-\x7e]|\\["\\])*)"'
_MEMBER = re.compile(r"\s*(" + _TOKEN + "|" + _STRING + ")")
_PARAMETER = re.compile(
    r"\s*;\s*([a-z*][a-z0-9_\-.*]*)(?:=(?:" + _STRING + r'|([^\s;,"]+)))?'
)
_SEPARATOR = re.compile(r"\s*,")
_STRING_ESCAPE = re.compile(r'\\(["\\])')


class _ProxyStatusMember(NamedTuple):
    name: str
    raw: str
    parameters: dict[str, str]


def _parse_proxy_status(value: str) -> list[_ProxyStatusMember]:
    """Parse members up to the first malformed one; later members are dropped."""
    members: list[_ProxyStatusMember] = []
    position = 0
    while (member := _MEMBER.match(value, position)) is not None:
        start, position = member.start(1), member.end()
        parameters: dict[str, str] = {}
        while (parameter := _PARAMETER.match(value, position)) is not None:
            key, string_item, bare_item = parameter.groups()
            if string_item is not None:
                parameters[key] = _STRING_ESCAPE.sub(r"\1", string_item)
            else:
                parameters[key] = bare_item if bare_item is not None else "?1"
            position = parameter.end()
        members.append(
            _ProxyStatusMember(member.group(1), value[start:position], parameters)
        )
        if (separator := _SEPARATOR.match(value, position)) is None:
            break
        position = separator.end()
    return members


class ConnectorsGatewayError(httpx.HTTPStatusError):
    """An HTTP error generated by Connectors Gateway rather than the upstream."""

    def __init__(
        self,
        *,
        response: httpx.Response,
        proxy_status: str,
        proxy_error: str,
        proxy_status_code: int | None,
        details: str | None,
    ) -> None:
        message = (
            f"Connectors Gateway request failed with status "
            f"{response.status_code}: {details or proxy_error}"
        )
        super().__init__(message, request=response.request, response=response)
        self.proxy_status = proxy_status
        self.proxy_error = proxy_error
        self.proxy_status_code = proxy_status_code
        self.details = details


async def raise_connectors_gateway_error(response: httpx.Response) -> None:
    """Raise for a gateway-authored error while leaving upstream errors unchanged."""
    if not response.is_error:
        return

    for value in response.headers.get_list("proxy-status"):
        for member in _parse_proxy_status(value):
            proxy_error = member.parameters.get("error")
            if member.name != _GATEWAY_MEMBER or proxy_error is None:
                continue

            await response.aread()
            raw_status_code = member.parameters.get("status-code", "")
            raise ConnectorsGatewayError(
                response=response,
                proxy_status=member.raw,
                proxy_error=proxy_error,
                proxy_status_code=(
                    int(raw_status_code) if raw_status_code.isdecimal() else None
                ),
                details=member.parameters.get("details"),
            )


def single_connectors_gateway_error(
    error: BaseException,
) -> ConnectorsGatewayError | None:
    """Unwrap the single-child exception groups produced by MCP's task group."""
    while not isinstance(error, ConnectorsGatewayError):
        nested_errors = getattr(error, "exceptions", None)
        if not isinstance(nested_errors, tuple) or len(nested_errors) != 1:
            return None
        error = nested_errors[0]
    return error
